#!/usr/bin/env python3
"""Task B6 — dataset statistics. Write it once, properly; the paper needs it verbatim.

WHAT THIS TELLS YOU (beyond filling a table)
--------------------------------------------
* **relevant-docs-per-query distribution** -> sets the ceiling on Precision at any
  fixed k, and tells you what `min_k`/`max_k` should be in the cutoff rule. If
  85% of queries have exactly 1 relevant document, returning 10 caps macro
  Precision at 0.10 and a `ratio` cutoff will beat any fixed k by a mile.
* **article length p99** -> whether documents overflow your encoder's max
  sequence length. PhoBERT-base is 256 tokens; BGE-M3 is 8192. If p99 is 900
  words, a PhoBERT bi-encoder is silently truncating most of your corpus and
  chunking is not optional.
* **query length** -> short keyword-ish queries favour BM25; long natural
  questions favour dense retrieval. This predicts your fusion weight.
* **corpus size x query count** -> the number you need for the Phase 2
  self-check on why a cross-encoder cannot score the full corpus.

USAGE
  python phases/0_harness/dataset_stats.py --out analysis/dataset_stats.md
"""
from __future__ import annotations

import argparse
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.abspath(  # repo root: phases/<n>_<name>/ -> ../..
    os.path.join(os.path.dirname(__file__), "..", "..")))

from src import io_utils  # noqa: E402
from src.chunking import build_corpus  # noqa: E402


def describe(values, name):
    if not values:
        return {"name": name, "n": 0}
    v = sorted(values)
    n = len(v)
    def p(x): return v[min(int(x * n), n - 1)]
    return {"name": name, "n": n, "mean": sum(v) / n, "min": v[0],
            "p50": p(0.50), "p90": p(0.90), "p95": p(0.95), "p99": p(0.99),
            "max": v[-1]}


def row(d):
    return (f"| {d['name']} | {d['n']} | {d.get('mean',0):.1f} | {d.get('min',0)} | "
            f"{d.get('p50',0)} | {d.get('p90',0)} | {d.get('p95',0)} | "
            f"{d.get('p99',0)} | {d.get('max',0)} |")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--corpus", default="data/processed/corpus_document.jsonl")
    ap.add_argument("--queries", nargs="+",
                    default=["data/processed/queries_train.jsonl"])
    ap.add_argument("--out", default="work/analysis/dataset_stats.md")
    a = ap.parse_args()

    doc_ids, texts, _ = io_utils.load_corpus(a.corpus)
    recs = [{"doc_id": d, "text": t, "meta": {}} for d, t in zip(doc_ids, texts)]

    L = ["# Dataset statistics", "",
         f"Generated by `phases/0_harness/dataset_stats.py` from `{a.corpus}`.", "",
         "## 1. Corpus size by granularity", "",
         "| granularity | units | mean len (words) | p50 | p90 | p99 | max |",
         "|---|---|---|---|---|---|---|"]
    sizes = {}
    for g in ("document", "article", "clause"):
        c = build_corpus(recs, g)
        lens = [len(r["text"].split()) for r in c]
        d = describe(lens, g)
        sizes[g] = len(c)
        L.append(f"| {g} | {len(c)} | {d['mean']:.1f} | {d['p50']} | {d['p90']} "
                 f"| {d['p99']} | {d['max']} |")

    L += ["", "> **Read this against your encoder's max sequence length.** "
              "PhoBERT-base = 256 tokens (~180 Vietnamese words); BGE-M3 = 8192. "
              "Any granularity whose p90 exceeds the limit is being truncated.", ""]

    L += ["## 2. Length distributions", "",
          "| series | n | mean | min | p50 | p90 | p95 | p99 | max |",
          "|---|---|---|---|---|---|---|---|---|",
          row(describe([len(t.split()) for t in texts], "document (words)"))]

    for qp in a.queries:
        if not os.path.exists(qp):
            print(f"skip missing {qp}", file=sys.stderr)
            continue
        qs = io_utils.load_queries(qp)
        tag = os.path.basename(qp).replace(".jsonl", "")
        L.append(row(describe([len(q["text"].split()) for q in qs], f"{tag} query (words)")))
        L.append(row(describe([len(q["relevant"]) for q in qs], f"{tag} |relevant|")))

    L += ["", "## 3. Relevant documents per query", ""]
    for qp in a.queries:
        if not os.path.exists(qp):
            continue
        qs = io_utils.load_queries(qp)
        c = Counter(len(q["relevant"]) for q in qs)
        tot = sum(c.values())
        L += [f"### {os.path.basename(qp)}  ({tot} queries)", "",
              "| |relevant| | queries | share | cumulative |", "|---|---|---|---|"]
        cum = 0
        for k in sorted(c):
            cum += c[k]
            L.append(f"| {k} | {c[k]} | {100*c[k]/tot:.1f}% | {100*cum/tot:.1f}% |")
        L += ["", f"Mean relevant/query: **{sum(k*v for k,v in c.items())/tot:.2f}**", ""]
        share1 = 100 * c.get(1, 0) / tot
        L.append(f"> {share1:.0f}% of queries have exactly one relevant document. "
                 f"A fixed top-k of {10} therefore caps macro Precision at "
                 f"{1/10:.2f} for those queries — which is the whole argument for a "
                 f"variable-length answer set (`src/cutoff.py`).")

    L += ["", "## 4. Numbers you will need later", "",
          f"- Corpus units (document / article / clause): "
          f"**{sizes['document']} / {sizes['article']} / {sizes['clause']}**"]
    nq = sum(len(io_utils.load_queries(q)) for q in a.queries if os.path.exists(q))
    L.append(f"- Labelled queries: **{nq}**")
    L.append(f"- Full cross-encoder pass over the article-level corpus: "
             f"**{nq} x {sizes['article']} = {nq*sizes['article']:,} pairs** "
             f"(Phase 2 self-check — see why retrieve-then-rerank exists).")

    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwrote {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
